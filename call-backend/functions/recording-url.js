/*
 * POST /recording-url  { passcode, action, id }  ->  { url }
 *
 * Lets the dashboard store and play call recordings in a PRIVATE Supabase
 * Storage bucket using only your passcode.
 *
 * The bucket has no public access and no rule for the dashboard's public key,
 * so the page itself can't read or write it. This function holds the only key
 * that can (SUPABASE_SERVICE_KEY, secret, set only here) and, once the passcode
 * checks out, hands back a link good for ONE thing: a single upload, a single
 * download (5 minutes), or a delete. Nothing it returns opens any other file.
 *
 * Environment: CALL_PASSCODE, ALLOWED_ORIGINS (as /token), SUPABASE_URL,
 * SUPABASE_SERVICE_KEY. Bucket name defaults to signalboard-recordings.
 */
const crypto = require("crypto");

const BUCKET = "signalboard-recordings";

function list(value) {
  return String(value || "").split(",").map((s) => s.trim()).filter(Boolean);
}

function passcodeMatches(given, expected) {
  if (typeof given !== "string" || typeof expected !== "string" || !expected) return false;
  const a = crypto.createHash("sha256").update(given).digest();
  const b = crypto.createHash("sha256").update(expected).digest();
  return crypto.timingSafeEqual(a, b);
}

exports.handler = async function (context, event, callback) {
  const response = new Twilio.Response();
  const origin = (event.request && event.request.headers && event.request.headers.origin) || "";
  const allowedOrigins = list(context.ALLOWED_ORIGINS);

  if (allowedOrigins.includes(origin)) {
    response.appendHeader("Access-Control-Allow-Origin", origin);
    response.appendHeader("Vary", "Origin");
  }
  response.appendHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
  response.appendHeader("Access-Control-Allow-Headers", "Content-Type");
  response.appendHeader("Content-Type", "application/json");
  response.appendHeader("Cache-Control", "no-store");

  const fail = (status, message) => {
    response.setStatusCode(status);
    response.setBody({ error: message });
    return callback(null, response);
  };

  if (!allowedOrigins.includes(origin)) return fail(403, "Origin not allowed.");
  if (!context.SUPABASE_URL || !context.SUPABASE_SERVICE_KEY) {
    return fail(500, "Backend not configured: missing SUPABASE_URL or SUPABASE_SERVICE_KEY.");
  }
  if (!passcodeMatches(event.passcode, context.CALL_PASSCODE)) return fail(401, "Wrong passcode.");

  // The id is generated by the dashboard (a UUID). Checking its shape keeps
  // anything else, like "../", from ever reaching the storage path.
  const id = String(event.id || "");
  if (!/^[A-Za-z0-9-]{8,64}$/.test(id)) return fail(400, "Bad recording id.");
  const action = String(event.action || "");
  if (!["upload", "download", "delete"].includes(action)) return fail(400, "Unknown action.");

  const base = context.SUPABASE_URL.replace(/\/+$/, "") + "/storage/v1";
  const path = BUCKET + "/" + id + ".webm";
  const auth = { apikey: context.SUPABASE_SERVICE_KEY, Authorization: "Bearer " + context.SUPABASE_SERVICE_KEY };

  try {
    if (action === "upload") {
      const r = await fetch(base + "/object/upload/sign/" + path, {
        method: "POST",
        headers: { ...auth, "Content-Type": "application/json", "x-upsert": "true" },
        body: "{}",
      });
      const d = await r.json().catch(() => ({}));
      if (!r.ok || !d.url) return fail(502, "Storage refused to start the upload (" + r.status + ").");
      response.setBody({ url: base + d.url });
      return callback(null, response);
    }

    if (action === "download") {
      const r = await fetch(base + "/object/sign/" + path, {
        method: "POST",
        headers: { ...auth, "Content-Type": "application/json" },
        body: JSON.stringify({ expiresIn: 300 }),
      });
      if (r.status === 404 || r.status === 400) return fail(404, "No such recording.");
      const d = await r.json().catch(() => ({}));
      if (!r.ok || !d.signedURL) return fail(502, "Storage refused the download (" + r.status + ").");
      response.setBody({ url: base + d.signedURL });
      return callback(null, response);
    }

    const r = await fetch(base + "/object/" + path, { method: "DELETE", headers: auth });
    response.setBody({ ok: r.ok || r.status === 404 });
    return callback(null, response);
  } catch (err) {
    return fail(502, "Couldn't reach storage.");
  }
};
